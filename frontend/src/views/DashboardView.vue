<script setup>
import { onMounted, ref } from 'vue'
import DetectionTable from '../components/DetectionTable.vue'
import StatTile from '../components/StatTile.vue'
import { api, errorMessage } from '../services/api'
import { pct, seconds } from '../services/format'

const health = ref(null)
const stats = ref(null)
const recent = ref([])
const loading = ref(true)
const error = ref('')

onMounted(async () => {
  try {
    const [h, s, r] = await Promise.all([api.health(), api.statistics(), api.detections({ limit: 5 })])
    health.value = h
    stats.value = s
    recent.value = r.items
  } catch (e) {
    error.value = errorMessage(e)
  } finally {
    loading.value = false
  }
})
</script>

<template>
  <div class="space-y-6">
    <section class="flex flex-col gap-4 sm:flex-row sm:items-end sm:justify-between">
      <div>
        <h1 class="text-2xl font-semibold text-slate-900">Dashboard</h1>
        <p class="mt-1 text-sm text-slate-600">Check whether an image was likely generated by AI, using open-source models on this computer.</p>
      </div>
      <RouterLink to="/detect" class="btn-primary self-start">Analyse an image</RouterLink>
    </section>

    <p v-if="error" class="rounded-lg border border-red-200 bg-red-50 p-3 text-sm text-red-800" role="alert">{{ error }}</p>

    <section v-if="health" class="card flex flex-wrap items-center gap-x-6 gap-y-2 !py-3 text-sm">
      <span class="flex items-center gap-2 font-medium">
        <span class="h-2.5 w-2.5 rounded-full" :class="health.model_loaded ? 'bg-real' : 'bg-ai'" aria-hidden="true" />
        Backend {{ health.model_loaded ? 'ready' : 'running, model not loaded' }}
      </span>
      <span v-if="health.model_version" class="text-slate-600">Model: <b>{{ health.model_version }}</b></span>
      <span v-if="health.device" class="text-slate-600">Device: <b>{{ health.device }}</b></span>
      <span v-if="health.thresholds" class="text-slate-600">
        Uncertain band: {{ pct(health.thresholds.t_low, 0) }} – {{ pct(health.thresholds.t_high, 0) }} AI probability
      </span>
      <span v-if="health.error" class="text-red-700">{{ health.error }}</span>
    </section>

    <section class="grid grid-cols-2 gap-3 md:grid-cols-3 lg:grid-cols-6">
      <StatTile label="Images analysed" :value="stats?.total ?? '—'" :loading="loading" />
      <StatTile label="AI generated" :value="stats?.ai_generated ?? '—'" :loading="loading" />
      <StatTile label="Real" :value="stats?.real ?? '—'" :loading="loading" />
      <StatTile label="Uncertain" :value="stats?.uncertain ?? '—'" :loading="loading" />
      <StatTile label="Avg. confidence" :value="pct(stats?.average_confidence)" :loading="loading" />
      <StatTile label="Avg. time" :value="seconds(stats?.average_processing_time_ms)" :loading="loading" />
    </section>

    <section class="card">
      <div class="mb-3 flex items-center justify-between">
        <h2 class="font-semibold">Recent detections</h2>
        <RouterLink to="/history" class="text-sm font-medium text-indigo-700 hover:underline">View all</RouterLink>
      </div>
      <DetectionTable v-if="recent.length" :items="recent" compact />
      <p v-else-if="!loading" class="py-6 text-center text-sm text-slate-500">
        No images analysed yet. <RouterLink to="/detect" class="text-indigo-700 hover:underline">Analyse your first image</RouterLink>.
      </p>
    </section>
  </div>
</template>
